// Generates what the package data implies, so nothing is listed by hand:
//   * the per-package quick stages in .st-check.toml (between the markers),
//   * the per-package Biome noRestrictedImports overrides (editor feedback).
//
//   node scripts/check-stages.mjs          write both
//   node scripts/check-stages.mjs --check  exit 1 when either is stale (boundaries.mjs runs this)
//
// Stage shape: one quick stage per package and tool, run when the package or a
// package it depends on changed (quick_paths). Each is focused and optional, and
// `covered_by` the whole-repo stage of the same tool, so the full gate runs the
// whole-repo stage once and nothing loses coverage.
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const { loadPackages, cone, contractReaders, ROOT_FILES } = createRequire(import.meta.url)(
  './packages.cjs',
)
const root = fileURLToPath(new URL('..', import.meta.url))
const BEGIN =
  '# BEGIN generated by scripts/check-stages.mjs (npm run check-stages); do not edit by hand'
const END = '# END generated'

const q = (value) => JSON.stringify(value)
const list = (values) => `[${values.map(q).join(', ')}]`

function stage(id, { quickPaths, argv, coveredBy, timeout }) {
  return [
    '[[native.stages]]',
    `id = ${q(id)}`,
    'kind = "check"',
    'coverage = "focused"',
    'required = false',
    ...(coveredBy ? [`covered_by = ${q(coveredBy)}`] : []),
    'quick = true',
    `quick_paths = ${list(quickPaths)}`,
    `argv = ${list(argv)}`,
    ...(timeout ? [`timeout_seconds = ${timeout}`] : []),
    '',
  ].join('\n')
}

export function tomlBlock(packages = loadPackages(root)) {
  const { readers } = contractReaders(root)
  const bin = (name) => `node_modules/.bin/${name}`
  const out = []
  for (const pkg of packages) {
    const reads = readers.some((row) => row.kind === 'package' && row.dir === pkg.dir)
    const quickPaths = [
      ...cone(packages, pkg).map((item) => `packages/${item.dir}/**`),
      ...ROOT_FILES,
      ...(reads ? ['contracts/**'] : []),
    ]
    const dir = `packages/${pkg.dir}`
    out.push(
      stage(`biome-${pkg.dir}`, {
        quickPaths,
        coveredBy: 'biome',
        argv: [bin('biome'), 'check', dir],
      }),
      stage(`tsc-${pkg.dir}`, { quickPaths, coveredBy: 'tsc', argv: [bin('tsc'), '-b', dir] }),
      stage(`vitest-${pkg.dir}`, {
        quickPaths,
        coveredBy: 'vitest',
        argv: [
          'bash',
          '-c',
          `PATH=$PATH:/usr/bin:/bin TMPDIR=/tmp exec ${bin('vitest')} run --project ${pkg.dir}`,
        ],
        timeout: 900,
      }),
      stage(`depcruise-${pkg.dir}`, {
        quickPaths,
        coveredBy: 'depcruise',
        argv: [bin('depcruise'), dir, '--config', '.dependency-cruiser.cjs', '--ignore-known'],
      }),
    )
  }
  // Native dirs run only when native/<dir> or the fixture they read changes. Python
  // and shell otherwise stay on the repo-wide ruff, ty and pytest, which already
  // select by changed path; the stage here is the contracts/ fixture test.
  for (const row of readers.filter((item) => item.kind === 'native')) {
    const tests = row.readers.filter((file) => /\/tests\/test_[^/]+\.py$/.test(file))
    if (tests.length === 0) continue
    out.push(
      stage(`contracts-${row.dir}`, {
        quickPaths: [`native/${row.dir}/**`, 'contracts/**'],
        argv: [`native/${row.dir}/.venv/bin/pytest`, '-q', ...tests],
      }),
    )
  }
  return `${BEGIN}\n${out.join('\n')}${END}`
}

// Biome only reads a nested biome.json for the files under it, so a package that
// has one carries its own overrides; the others share the root file.
export function biomeOverrides(packages = loadPackages(root)) {
  const forPackage = (pkg, nested) => {
    const others = packages.filter(
      (other) => other.dir !== pkg.dir && !pkg.allow.includes(other.name),
    )
    const message = (text) => `${pkg.name} (layer ${pkg.layer}): ${text}`
    const groups = (names, why) =>
      names.length
        ? [{ group: names.flatMap((name) => [name, `${name}/**`]), message: message(why) }]
        : []
    const upward = others.filter((other) => other.layer >= pkg.layer).map((other) => other.name)
    const servers = pkg.browser
      ? others.filter((other) => other.layer === 5).map((other) => other.name)
      : []
    const patterns = [
      ...groups(upward, 'import only packages in lower layers (depcruise is the gate)'),
      ...groups(
        servers.filter((name) => !upward.includes(name)),
        'browser code never imports a server package',
      ),
      ...(pkg.browser
        ? [{ group: ['node:*'], message: message('browser code has no node:* modules') }]
        : []),
    ]
    const base = nested ? '**' : `packages/${pkg.dir}/**`
    return {
      includes: [
        base,
        ...(pkg.browser
          ? ['!**/*.test.*', '!**/*.config.*', '!**/scripts/**', '!**/test-stubs/**']
          : []),
      ],
      linter: {
        rules: {
          style: {
            noRestrictedImports: {
              level: 'warn',
              options: {
                paths: { 'node:sqlite': 'Only the store package imports node:sqlite.' },
                patterns,
              },
            },
          },
        },
      },
    }
  }
  const files = new Map()
  for (const pkg of packages) {
    const nested = existsSync(join(root, 'packages', pkg.dir, 'biome.json'))
    const file = nested ? `packages/${pkg.dir}/biome.json` : 'biome.json'
    files.set(file, [...(files.get(file) ?? []), forPackage(pkg, nested)])
  }
  return files
}

const readJson = (file) => JSON.parse(readFileSync(join(root, file), 'utf8'))
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b)

// Names of the files that no longer match their package data.
export function stale() {
  const packages = loadPackages(root)
  const result = []
  const toml = readFileSync(join(root, '.st-check.toml'), 'utf8')
  const start = toml.indexOf(BEGIN)
  const end = toml.indexOf(END)
  if (start < 0 || end < start || toml.slice(start, end + END.length) !== tomlBlock(packages))
    result.push('.st-check.toml')
  for (const [file, overrides] of biomeOverrides(packages)) {
    if (!same(readJson(file).overrides, overrides)) result.push(file)
  }
  return result
}

function write() {
  const packages = loadPackages(root)
  const path = join(root, '.st-check.toml')
  const toml = readFileSync(path, 'utf8')
  const block = tomlBlock(packages)
  const start = toml.indexOf(BEGIN)
  const end = toml.indexOf(END)
  const next =
    start >= 0 && end > start
      ? toml.slice(0, start) + block + toml.slice(end + END.length)
      : toml.replace('[[deep.stages]]', `${block}\n\n[[deep.stages]]`)
  writeFileSync(path, next)
  const touched = []
  for (const [file, overrides] of biomeOverrides(packages)) {
    writeFileSync(
      join(root, file),
      `${JSON.stringify({ ...readJson(file), overrides }, null, 2)}\n`,
    )
    touched.push(file)
  }
  // The files stay in Biome's own format.
  execFileSync(
    join(root, 'node_modules/.bin/biome'),
    ['format', '--write', ...touched.map((f) => join(root, f))],
    {
      cwd: root,
      stdio: 'ignore',
    },
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const files = stale()
    if (files.length) {
      console.error(`stale, run npm run check-stages: ${files.join(', ')}`)
      process.exit(1)
    }
  } else write()
}
